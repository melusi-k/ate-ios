#!/usr/bin/env python3
"""Generates Ate/Logic/BetaChecklist.swift from the Tier A section of docs/MVP_CHECKLIST.md."""
import re, json, os
os.chdir(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
s = open('docs/MVP_CHECKLIST.md').read()
a = s.split('## Tier A')[1].split('## Tier B')[0]
auto = {"A-CREATE-01","A-CREATE-02","A-CREATE-03","A-CREATE-04","A-CREATE-06","A-EDIT-01","A-EDIT-02","A-EDIT-03","A-EDIT-04",
        "A-AUTH-01","A-AUTH-02","A-AUTH-03","A-AUTH-04","A-AUTH-05","A-AUTH-06","A-AUTH-08","A-SYNC-01","A-SYNC-04","A-SYNC-05",
        "A-SHARE-01","A-SHARE-02","A-SHARE-05","A-TIMER-01","A-TIMER-02","A-TIMER-03","A-OFF-02","A-REL-01","A-CI-01","A-LAUNCH-01","A-HEALTH-03","A-HEALTH-04","A-HEALTH-05","A-HEALTH-08",
        "A-WIDGET-01","A-WIDGET-02","A-WIDGET-03","A-WIDGET-04","A-CONTROL-01","A-INTENT-02","A-INTENT-03","A-INTENT-04","A-INTENT-05","A-COVER-01"}
def parse(sec, prefix, autoset):
    cat = None; out = []
    for blk in re.split(r'\n(?=### |- \*\*%s-)' % prefix, sec):
        m = re.match(r'### (.+?) —', blk)
        if m: cat = re.sub(r'\s*\(.*?\)', '', m.group(1)).strip(); continue
        m = re.match(r'- \*\*(%s-[A-Z]+-\d+) · (.+?)\*\*' % prefix, blk)
        if m:
            acc = re.search(r'\*Acceptance:\* (.+)', blk)
            ver = re.search(r'\*Verified by:\* (.+)', blk)
            isauto = m.group(1) in autoset or bool(ver and ver.group(1).strip().startswith('auto'))
            out.append((m.group(1), m.group(2), cat, acc.group(1).strip() if acc else '', isauto))
    return out
outA = parse(a, 'A', auto)
c = s.split('## Tier C')[1].split('## Privacy-language audit')[0]
outC = parse(c, 'C', set())
q = lambda x: json.dumps(x, ensure_ascii=False)
lines = ["// GENERATED by scripts/gen-beta-checklist.py from docs/MVP_CHECKLIST.md (Tier A + Tier C). Do not edit by hand.",
         "import Foundation", "", "struct BetaItem: Identifiable, Hashable {",
         "    let id: String; let title: String; let category: String; let how: String; let auto: Bool", "}", "",
         "enum BetaChecklist {"]
for name, rows in (("tierA", outA), ("tierC", outC)):
    lines.append(f"    static let {name}: [BetaItem] = [")
    for i, t, cc, h, au in rows:
        lines.append(f"        BetaItem(id: {q(i)}, title: {q(t)}, category: {q(cc)}, how: {q(h)}, auto: {'true' if au else 'false'}),")
    lines.append("    ]")
lines += ["    /// The checklist for this build's channel: TierC builds test the Tier C polish items, everything else Tier A.",
          "    static var isTierC: Bool { AppConfig.channel.uppercased() == \"TIERC\" }",
          "    static var tierName: String { isTierC ? \"Tier C\" : \"Tier A\" }",
          "    static var items: [BetaItem] { isTierC ? tierC : tierA }",
          "    static var all: [BetaItem] { tierA + tierC }","    static var categories: [String] { var seen: [String] = []; for i in items where !seen.contains(i.category) { seen.append(i.category) }; return seen }", "}"]
open('Ate/Logic/BetaChecklist.swift', 'w').write("\n".join(lines) + "\n")
print(len(outA), "Tier A items,", len(outC), "Tier C items")
