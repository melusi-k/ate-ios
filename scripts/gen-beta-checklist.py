#!/usr/bin/env python3
"""Generate BetaChecklist.swift from the unified feature-area backlog."""
import re, json, os
os.chdir(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
s = open('docs/MVP_CHECKLIST.md').read()
unified = s.split('## Unified backlog by feature area', 1)[1].split('## Privacy-language audit', 1)[0]
auto = {"A-CREATE-01","A-CREATE-02","A-CREATE-03","A-CREATE-04","A-CREATE-06","A-EDIT-01","A-EDIT-02","A-EDIT-03","A-EDIT-04",
        "A-AUTH-01","A-AUTH-02","A-AUTH-03","A-AUTH-04","A-AUTH-05","A-AUTH-06","A-AUTH-08","A-SYNC-01","A-SYNC-04","A-SYNC-05",
        "A-SHARE-01","A-SHARE-02","A-SHARE-05","A-TIMER-01","A-TIMER-02","A-TIMER-03","A-OFF-02","A-REL-01","A-CI-01","A-LAUNCH-01","A-HEALTH-03","A-HEALTH-04","A-HEALTH-05","A-HEALTH-08",
        "A-WIDGET-01","A-WIDGET-02","A-WIDGET-03","A-WIDGET-04","A-CONTROL-01","A-INTENT-02","A-INTENT-03","A-INTENT-04","A-INTENT-05","A-COVER-01"}
def parse(gate):
    cat = None
    out = []
    for blk in re.split(r'\\n(?=#### |- \\*\\*[ABC]-)', unified):
        m = re.match(r'#### (.+)', blk)
        if m:
            cat = re.sub(r'\\s*\\(.*?\\)', '', m.group(1)).strip()
            continue
        m = re.match(r'- \\*\\*([ABC]-[A-Z0-9]+-\\d{2}) · (.+?)\\*\\*', blk)
        if not m:
            continue
        gm = re.search(r'\\*Release gate:\\* (.*?) ·', blk)
        if not gm or gm.group(1).strip() != gate:
            continue
        acc = re.search(r'\\*Acceptance:\\* (.+)', blk)
        ver = re.search(r'\\*Verified by:\\* (.+)', blk)
        isauto = m.group(1) in auto or bool(ver and ver.group(1).strip().startswith('auto'))
        out.append((m.group(1), m.group(2), cat or 'General', acc.group(1).strip() if acc else '', isauto))
    return out
outA = parse('Pilot')
outC = parse('No committed release gate')
q = lambda x: json.dumps(x, ensure_ascii=False)
lines = ["// GENERATED by scripts/gen-beta-checklist.py from docs/MVP_CHECKLIST.md unified feature-area backlog. Do not edit by hand.",
         "import Foundation", "", "struct BetaItem: Identifiable, Hashable {",
         "    let id: String; let title: String; let category: String; let how: String; let auto: Bool", "}", "",
         "enum BetaChecklist {"]
for name, rows in (("tierA", outA), ("tierC", outC)):
    lines.append(f"    static let {name}: [BetaItem] = [")
    for i, title, category, how, au in rows:
        lines.append(f"        BetaItem(id: {q(i)}, title: {q(title)}, category: {q(category)}, how: {q(how)}, auto: {'true' if au else 'false'}),")
    lines.append("    ]")
lines += ["    /// The checklist for this build channel: pilot builds show Pilot-gate items; TierC compatibility builds show uncommitted-gate items.",
          "    static var isTierC: Bool { AppConfig.channel.uppercased() == \"TIERC\" }",
          "    static var tierName: String { isTierC ? \"Uncommitted work\" : \"Pilot gate\" }",
          "    static var items: [BetaItem] { isTierC ? tierC : tierA }",
          "    static var all: [BetaItem] { tierA + tierC }",
          "    static var categories: [String] { var seen: [String] = []; for i in items where !seen.contains(i.category) { seen.append(i.category) }; return seen }", "}"]
open('Ate/Logic/BetaChecklist.swift', 'w').write("\\n".join(lines) + "\\n")
print(len(outA), "Pilot-gate items,", len(outC), "uncommitted-gate items")
